"""Write the twenty-question eval result to `docs/data/eval.json`, with its provenance.

This is the eval's result, and the only place it is published. It used to be restated as a table
in `eval-output.md`, which went stale once already — regenerated by hand after Q19 and Q20 were
added, and nothing would have caught it if that had been forgotten.

This is the eval's counterpart to `publish_figures.py`, and the split is deliberate: the eval
depends on the **bundle** as well as the cluster, so a bundle edit should invalidate the eval
without touching a single published figure.

Two tests read the result. One holds it to what `docs/specs/eval.md` declares and needs no
credentials, so a bare clone still catches a record that drifted from the spec. The other re-runs
the eval against the cluster and asserts it still reproduces, which is what catches a record that
is faithful to a result that is no longer true.

    uv run --extra es python scripts/publish_eval.py [--check]
"""
from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from grounded_context.es_client import INDEX, is_configured
from grounded_context.evaluation import run_all
from grounded_context.service import as_of_date, bundle_root, load_bundle
from publish_figures import git_sha

DATA_FILE = Path(__file__).resolve().parents[1] / "docs" / "data" / "eval.json"


def build() -> dict[str, Any]:
    """Every case's outcome, plus what a reader needs to judge whether it still holds."""
    bundle = load_bundle(None)
    results = run_all(bundle, as_of_date(None))
    rows = [r.as_dict() for r in results]
    verdicts = [r["verdict"] for r in rows]
    return {
        "run": {
            "measured_at": datetime.now(UTC).date().isoformat(),
            "bundle": str(bundle_root(None).name),
            "concepts": len(bundle),
            "index": INDEX,
            # A run without the cluster silently turns every semantic case into a refusal, so
            # whether it was reachable is part of the result rather than a footnote about it.
            "elasticsearch_configured": is_configured(),
            "git_sha": git_sha(),
        },
        "totals": {
            "pass": verdicts.count("PASS"),
            "known": verdicts.count("KNOWN"),
            "fail": verdicts.count("FAIL"),
        },
        "cases": rows,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="re-run and report whether any verdict moved, without writing",
    )
    args = parser.parse_args(argv)

    fresh = build()
    if not fresh["run"]["elasticsearch_configured"]:
        print("error: no cluster configured — every semantic case would record a false refusal")
        return 1

    if not args.check:
        DATA_FILE.parent.mkdir(parents=True, exist_ok=True)
        DATA_FILE.write_text(json.dumps(fresh, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {DATA_FILE.name}: " + " · ".join(
            f"{count} {name}" for name, count in fresh["totals"].items()
        ))
        return 0

    if not DATA_FILE.exists():
        print(f"error: {DATA_FILE} does not exist — run without --check first")
        return 1
    committed = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    moved = [
        key for key in ("totals", "cases") if committed.get(key) != fresh.get(key)
    ]
    if moved:
        print("eval moved since the committed run: " + ", ".join(moved))
        return 1
    print(f"the eval reproduces (committed {committed['run']['measured_at']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
